export function getInitialProducts() {
  if (typeof window !== 'undefined') {
    try {
      const saved = localStorage.getItem('rb_custom_products');
      if (saved) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length > 0) {
          return parsed;
        }
      }
    } catch (e) {
      console.warn('Error reading stored products:', e);
    }
  }
  return [...INITIAL_PRODUCTS];
}

export const PRODUCTS = getInitialProducts();

export function syncProductsArray(newList) {
  if (Array.isArray(newList)) {
    PRODUCTS.length = 0;
    PRODUCTS.push(...newList);
  }
}

